/* Frontend build — bundle the ES-module sources (public/js/*.jsx) into public/app.js.

   History: this started as in-browser babel; then a build step that indirect-eval'd
   each file to preserve the old global-scope semantics; now the files are real ES
   modules (import/export) and esbuild bundles them properly (one scope, no eval,
   real sourcemaps). Third-party libs (React, ReactDOM, marked, DOMPurify, katex,
   leaflet) remain <script> globals from index.html and are referenced as free
   identifiers — esbuild leaves them unbundled.

   Usage: node build/esbuild.mjs [--watch] [--minify]
*/
import { writeFile } from "fs/promises";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { build } from "esbuild";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const JS_DIR = path.join(ROOT, "public", "js");
const OUT = path.join(ROOT, "public", "app.js");

// Module evaluation order. esbuild resolves the import graph itself, so this only
// needs to (a) include every file so none is tree-shaken away, and (b) keep app.jsx
// LAST — its top-level ReactDOM.createRoot(...).render() mounts the app, and must run
// after every component module it pulls in has evaluated.
const ORDER = [
  "icons", "auth", "image-edit", "gallery", "focus", "charts", "markdown", "renders", "chat-data", "chat-cards", "agent-trace", "chat-message", "composer", "chat-hooks", "chat", "settings", "manage",
  "folderpicker", "commandpalette", "chats", "projects", "agents", "setup",
  "quickask", "map", "people", "graph", "activity", "modals", "app-helpers", "app-hooks", "sidebar", "batch-bar", "gallery-topbar", "gallery-body", "source-drawer", "app",
];

const MINIFY = process.argv.includes("--minify");

// The frontend is real ES modules (public/js/*.jsx use import/export). esbuild bundles
// them from a generated entry into one IIFE → public/app.js, loaded by index.html as a
// classic <script>. Third-party libs (React, ReactDOM, marked, DOMPurify, katex, leaflet)
// stay as <script> globals from index.html and are referenced as free identifiers — they
// are NOT bundled. To add a file: just import/export it like the others (and add it to
// ORDER if nothing imports it yet, so it isn't dropped).
async function buildOnce() {
  const t0 = Date.now();
  // side-effect import every module (guarantees inclusion); app.jsx is last → mounts last.
  const entry = ORDER.map(n => `import "./${n}.jsx";`).join("\n");
  const res = await build({
    stdin: { contents: entry, resolveDir: JS_DIR, loader: "js", sourcefile: "entry.js" },
    bundle: true, write: false, format: "iife", logLevel: "warning",
    jsx: "transform",                 // classic runtime → React.createElement (React is a <script> global)
    jsxFactory: "React.createElement",
    jsxFragment: "React.Fragment",
    loader: { ".jsx": "jsx" },
    minify: MINIFY,
    sourcemap: MINIFY ? false : "inline",   // real sourcemaps in dev (no more eval/sourceURL)
    banner: { js: "/* AUTO-GENERATED by build/esbuild.mjs — do not edit. Source: public/js/*.jsx */" },
  });
  await writeFile(OUT, res.outputFiles[0].text);
  console.log(`[build:ui] public/app.js  (${ORDER.length} modules, ${Date.now() - t0}ms${MINIFY ? ", minified" : ""})`);
}

async function main() {
  await buildOnce();
  if (process.argv.includes("--watch")) {
    console.log("[build:ui] watching public/js …");
    let timer = null;
    fs.watch(JS_DIR, { recursive: true }, (_e, f) => {
      if (!f || !f.endsWith(".jsx")) return;
      clearTimeout(timer);
      timer = setTimeout(() => buildOnce().catch(e => console.error("[build:ui]", e.message)), 120);
    });
  }
}
main().catch(e => { console.error("[build:ui] failed:", e.message); process.exit(1); });
